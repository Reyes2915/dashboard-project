export function buildSeed(): Expense[] {
  return ROWS.map(
    ([id, title, department, category, invoiceCode, netAmount, vatRate, date, status, justification, receiptUrl]) => ({
      id,
      title,
      department,
      category,
      invoiceCode,
      receiptUrl,
      netAmount,
      vatRate,
      totalAmount: computeTotal(netAmount, vatRate),
      date,
      justification,
      status,
      createdBy: 'u-seed',
      approvedBy: status === 'PENDING' ? null : 'u-admin',
      createdAt: `${date}T09:00:00.000Z`,
    }),
  );
}
